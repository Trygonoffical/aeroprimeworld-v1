create extension if not exists "pgcrypto";

create table if not exists public.shipments (
  id uuid primary key default gen_random_uuid(),
  tracking_number text unique not null,
  customer_name text not null,
  origin text not null,
  destination text not null,
  service text not null,
  status text not null default 'Label created',
  eta text not null,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.shipment_events (
  id bigint generated by default as identity primary key,
  shipment_id uuid not null references public.shipments(id) on delete cascade,
  status text not null,
  location text not null,
  note text default '',
  created_at timestamptz not null default now()
);

alter table public.shipments enable row level security;
alter table public.shipment_events enable row level security;

create policy "Public can read shipments by tracking number"
  on public.shipments for select using (true);
create policy "Public can read shipment events"
  on public.shipment_events for select using (true);

